def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _snapshot(root: Path, repo: str, revision: str, hashes: dict[str, str]) -> None:
    if (
        root.name != revision
        or root.parent.name != "snapshots"
        or root.parent.parent.name != "models--" + repo.replace("/", "--")
    ):
        raise ValueError(f"expected {repo}@{revision} Hub snapshot path: {root}")
    for name, expected in hashes.items():
        path = root / name
        if not path.is_file() or _sha256(path) != expected:
            raise ValueError(f"missing or wrong {repo}@{revision} {name}")


def validate_metadata(
    official: dict, quantized: dict, official_index: dict, quant_index: dict
) -> dict:
    """Fail closed on config drift, text key gaps or unexpected quantization layout."""
    if official.get("model_type") != "zdtaichu5_0" or official.get("architectures") != [
        "ZDTaichu5_0_ForConditionalGeneration"
    ]:
        raise ValueError("unexpected official Taichu architecture")
    q = quantized.get("quantization")
    if (
        q != {"group_size": 64, "bits": 4, "mode": "affine"}
        or quantized.get("quantization_config") != q
    ):
        raise ValueError("unexpected Taichu quantization contract")
    if {
        k: v
        for k, v in quantized.items()
        if k not in ("quantization", "quantization_config")
    } != official:
        raise ValueError("quantized Taichu config differs beyond quantization")
    text = official.get("llm_config")
    if (
        not isinstance(text, dict)
        or text.get("model_type") != "qwen3_5_text"
        or text.get("num_hidden_layers") != 32
    ):
        raise ValueError("unexpected pinned Taichu text config")
    layers = text.get("layer_types")
    if (
        layers
        != [
            "linear_attention",
            "linear_attention",
            "linear_attention",
            "full_attention",
        ]
        * 8
    ):
        raise ValueError("unexpected Taichu hybrid layer order")
    ow, qw = official_index.get("weight_map"), quant_index.get("weight_map")
    if not isinstance(ow, dict) or not isinstance(qw, dict):
        raise ValueError("missing safetensors weight_map")
    official_text = {k for k in ow if k.startswith("language_model.")}
    quant_text = {
        k
        for k in qw
        if k.startswith("language_model.") and not k.endswith((".scales", ".biases"))
    }
    if len(official_text) != 427 or quant_text != official_text:
        raise ValueError("Taichu text weight names differ from official pinned target")
    aux = {
        k
        for k in qw
        if k.startswith("language_model.") and k.endswith((".scales", ".biases"))
    }
    quantized_bases = {k.removesuffix(".scales") for k in aux if k.endswith(".scales")}
    if (
        len(quantized_bases) != 250
        or aux
        != {
            base + suffix
            for base in quantized_bases
            for suffix in (".scales", ".biases")
        }
        or any(base + ".weight" not in quant_text for base in quantized_bases)
    ):
        raise ValueError("unexpected Taichu quantization auxiliary names")
    if set(qw.values()) != set(SHARDS):
        raise ValueError("unexpected quantized shard manifest")
    if {
        k
        for k, shard in qw.items()
        if shard == "model-00005-of-00005.safetensors"
        and k.startswith("language_model.")
    } != {
        "language_model.lm_head.weight",
        "language_model.lm_head.scales",
        "language_model.lm_head.biases",
    }:
        raise ValueError("final shard does not contain expected LM head")
    nontext = {k for k in qw if not k.startswith("language_model.")}
    if not nontext or any(
        not k.startswith(("vision_model.", "mlp1.")) for k in nontext
    ):
        raise ValueError("unexpected non-text Taichu weight namespace")
    return {
        "model_type": "qwen3_5",
        "text_config": text,
        "quantization": q,
        "quantization_config": q,
        "eos_token_id": official["eos_token_id"],
        "pad_token_id": official["pad_token_id"],
        "model_file": "model.py",
    }


def prepare(official_root: Path, quant_root: Path, output: Path) -> None:
    official_root, quant_root, output = (
        official_root.absolute(),
        quant_root.absolute(),
        output.absolute(),
    )
    _snapshot(official_root, OFFICIAL_REPO, OFFICIAL_REV, OFFICIAL_HASHES)
    _snapshot(quant_root, QUANT_REPO, QUANT_REV, QUANT_HASHES)
    with (official_root / "config.json").open() as f:
        official = json.load(f)
    with (quant_root / "config.json").open() as f:
        quant = json.load(f)
    with (official_root / "model.safetensors.index.json").open() as f:
        official_index = json.load(f)
    with (quant_root / "model.safetensors.index.json").open() as f:
        quant_index = json.load(f)
    derived = validate_metadata(official, quant, official_index, quant_index)
    for name, (size, digest) in SHARDS.items():
        path = quant_root / name
        if not path.is_file() or path.stat().st_size != size:
            raise ValueError(f"missing or truncated quantized shard: {path}")
        if _sha256(path) != digest:
            raise ValueError(f"wrong quantized shard SHA256: {path}")
    output.mkdir(parents=True, exist_ok=False)
    try:
        (output / "config.json").write_text(json.dumps(derived, indent=2) + "\n")
        (output / "model.py").write_text(MODEL_ADAPTER)
        for name in SHARDS:
            (output / name).symlink_to(quant_root / name)
        for name in ("tokenizer.json", "tokenizer_config.json", "chat_template.jinja"):
            (output / name).symlink_to(official_root / name)
        (output / "model.safetensors.index.json").symlink_to(
            quant_root / "model.safetensors.index.json"
        )
        (output / "source.json").write_text(
            json.dumps(
                {
                    "official": f"{OFFICIAL_REPO}@{OFFICIAL_REV}",
                    "quantized": f"{QUANT_REPO}@{QUANT_REV}",
                    "status": "metadata_prepared_weights_not_loaded",
                },
                indent=2,
            )
            + "\n"
        )
    except Exception:
        for child in output.iterdir():
            child.unlink()
        output.rmdir()
        raise


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--official-snapshot", type=Path, required=True)
    parser.add_argument("--quantized-snapshot", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    prepare(args.official_snapshot, args.quantized_snapshot, args.output)
    print(f"prepared metadata-only MLX target view: {args.output}")


if __name__ == "__main__":
    main()
